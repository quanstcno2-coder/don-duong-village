drop policy if exists "auth manage posts" on public.posts;
drop policy if exists "public read about blocks" on public.about_blocks;
drop policy if exists "auth manage about blocks" on public.about_blocks;
drop policy if exists "public create orders" on public.web_orders;
drop policy if exists "auth manage orders" on public.web_orders;
drop policy if exists "public create order items" on public.web_order_items;
drop policy if exists "auth manage order items" on public.web_order_items;

