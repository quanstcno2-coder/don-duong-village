create policy "auth manage sections" on public.page_sections for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

create policy "public read settings" on public.site_settings for select using (true);
create policy "auth manage settings" on public.site_settings for all to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);

create policy "public read published posts" on public.posts for select using (status='published');
