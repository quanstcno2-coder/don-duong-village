-- DON DUONG VILLAGE - Supabase setup
-- Chạy trong SQL Editor. Không cần service_role key trên website.

-- 1) Bổ sung cột cho bảng product hiện có
alter table public.product add column if not exists is_featured boolean default false;
alter table public.product add column if not exists slug text;
alter table public.product add column if not exists updated_at timestamptz default now();

-- 2) Nội dung website động
create table if not exists public.page_sections (
  id bigint generated by default as identity primary key,
  section_key text unique not null,
  title text,
  subtitle text,
  body text,
  image_url text,
  button_text text,
  button_url text,
  is_active boolean default true,
  sort_order integer default 0,
  updated_at timestamptz default now()
);

create table if not exists public.site_settings (
  id integer primary key default 1 check (id=1),
  brand_name text default 'DON DUONG VILLAGE',
  phone text,
  email text,
  address text,
  facebook_url text,
  tiktok_url text,
  shopee_url text,
  zalo_url text,
  support_hours text default '8:00 - 20:00',
  updated_at timestamptz default now()
);

insert into public.site_settings(id,brand_name) values(1,'DON DUONG VILLAGE')
on conflict (id) do nothing;

-- 3) Blog
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  title text not null,
  slug text unique not null,
  excerpt text,
  cover_url text,
  content_html text,
  status text default 'draft' check (status in ('draft','published')),
  published_at timestamptz
);


-- 3A) Nội dung trang Về chúng tôi (CRUD từ Admin)
create table if not exists public.about_blocks (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  block_type text not null default 'content'
    check (block_type in ('story','mission','vision','value','content')),
  title text not null,
  body text,
  image_url text,
  sort_order integer default 0,
  is_active boolean default true
);

-- 4) Đơn hàng + dòng sản phẩm
create table if not exists public.web_orders (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  customer_name text not null,
  phone text not null,
  email text,
  address text not null,
  note text,
  subtotal numeric default 0,
  shipping_fee numeric default 0,
  total numeric default 0,
  status text default 'new',
  payment_status text default 'unpaid'
);

create table if not exists public.web_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint references public.web_orders(id) on delete cascade,
  product_id bigint,
  product_name text not null,
  quantity integer not null check(quantity > 0),
  unit_price numeric not null,
  line_total numeric not null
);

-- 5) RLS
alter table public.product enable row level security;
alter table public.page_sections enable row level security;
alter table public.site_settings enable row level security;
alter table public.posts enable row level security;
alter table public.about_blocks enable row level security;
alter table public.web_orders enable row level security;
alter table public.web_order_items enable row level security;

